// ─── Hardware sub-types (from hardwares.proto) ───────────────────────────────

export type CPU = {
  id: string;
  brand: string;
  gen: string;
  family: string;
  series: string;
  cores: number;
  threads: number;
  base_clock: number;
  max_clock: number;
  cache: number;
  socket: string;
  graphics: boolean;
  oc: boolean;
  recommended_power: number;
  avg_price: number;
};

export type GPU = {
  id: string;
  brand: string;
  family: string;
  series: string;
  memory_amount: number;
  memory_gen: string;
  cores: number;
  pci_express: number;
  recommended_power: number;
  avg_price: number;
};

export type RAMMemory = {
  id: string;
  brand: string;
  ddr: string;
  memory_amount: number;
  avg_price: number;
  frequency_mhz: number;
  series: string;
};


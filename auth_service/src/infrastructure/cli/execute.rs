use rpassword::read_password;

use crate::{
    application::commands::create_user::CreateUserCommand, domain::value_objects::role::Role,
    infrastructure::AppUserService,
};

pub async fn create_admin(app_user_service: AppUserService, username: &str, email: &str) {
    print_anime_girl();
    println!("⚙️  Initializing admin creation...");

    println!("Username: {}", username);
    println!("Email: {}", email);
    println!("Type admin password:");

    let password: String = read_password().expect("Failed to read password");

    let command: CreateUserCommand = CreateUserCommand::new(
        username.to_string(),
        email.to_string(),
        password,
        Role::Admin,
    );

    let output = app_user_service.create_user(command).await;

    match output {
        Ok(_) => {}
        Err(error) => {
            println!("Error: {}", error)
        }
    }

    println!("✅ Admin user created successfully!");
}

